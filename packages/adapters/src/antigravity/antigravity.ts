import type { ResolvedCdalConfig } from '@cdal/core';

export const ANTIGRAVITY_RULES_CHAR_LIMIT = 12000;

export const ANTIGRAVITY_TOOLS_MAP: Record<string, string> = {
  Read: 'view_file',
  Glob: 'find_by_name',
  Grep: 'grep_search',
  Write: 'write_to_file',
  Edit: 'replace_file_content',
  MultiEdit: 'multi_replace_file_content',
  Bash: 'run_command',
  Task: 'invoke_subagent',
  WebSearch: 'search_web',
  WebFetch: 'read_url_content',
};

const DEFAULT_CLAUDE_TOOLS_FOR_ROLE: Record<string, string[]> = {
  'spec-analyst': ['Read', 'Glob', 'Grep', 'Write', 'Edit'],
  'contract-steward': ['Read', 'Glob', 'Grep', 'Write', 'Edit', 'Bash'],
  'test-author': ['Read', 'Glob', 'Grep', 'Write', 'Edit', 'Bash'],
  implementer: ['Read', 'Glob', 'Grep', 'Write', 'Edit', 'Bash'],
  reviewer: ['Read', 'Glob', 'Grep', 'Bash'],
};

export function mapToolsToAntigravity(tools: string[]): string[] {
  const mapped = tools.map((t) => ANTIGRAVITY_TOOLS_MAP[t] || t).filter(Boolean);
  return [...new Set(mapped)];
}

export function generateAntigravityAgents(
  config: ResolvedCdalConfig,
): Array<{ path: string; content: string }> {
  const result: Array<{ path: string; content: string }> = [];

  const roles =
    Object.keys(config.roles).length > 0
      ? config.roles
      : {
          'spec-analyst': { write: ['docs/workorders/', '.cdal/state/'] },
          'contract-steward': { write: ['contracts/', 'src/generated/contracts/'] },
          'test-author': { write: ['tests/', '**/*.test.ts'] },
          implementer: { write: ['src/', 'app/'], denyTests: true },
          reviewer: { write: ['.cdal/memory/'] },
        };

  for (const [roleName, roleDef] of Object.entries(roles)) {
    const rawTools = DEFAULT_CLAUDE_TOOLS_FOR_ROLE[roleName] ?? [
      'Read',
      'Glob',
      'Grep',
      'Write',
      'Edit',
    ];
    const agTools = mapToolsToAntigravity(rawTools);
    const hasWrite = agTools.includes('write_to_file') || agTools.includes('replace_file_content');
    const hasBash = agTools.includes('run_command');

    const frontmatter = [
      '---',
      `name: ${roleName}`,
      `description: CDAL agent role for ${roleName}. Allowed write: ${roleDef.write.join(', ')}`,
      'tools:',
      ...agTools.map((t) => `  - ${t}`),
      'subagent: true',
      `mainAgent: ${roleName === 'spec-analyst' ? 'true' : 'false'}`,
      'model: inherit',
      `commandExecutionPolicy: ${hasBash ? 'sandbox' : '"off"'}`,
      '---',
      '',
    ].join('\n');

    const note = !hasWrite
      ? '\n> **This agent is read-only.** It cannot write or replace file contents. Document any recommendations in review summaries instead of attempting to write files.\n'
      : '\n> **Notice for Antigravity Runtime:** Pre-tool write interceptors may be runtime-dependent. Enforce boundaries by running `npx cdal phase <red|green>` after completion.\n';

    const body = `You are the ${roleName} agent in the CDAL workflow.
Allowed write scopes: ${roleDef.write.join(', ')}
${roleDef.denyTests ? 'Physical constraint: You are strictly forbidden from modifying test files.' : ''}

${note}`;

    const banner = '<!-- GENERATED by cdal sync — do not edit directly. -->\n';
    result.push({
      path: `.agents/agents/${roleName}.md`,
      content: `${frontmatter}${banner}\n${body.trim()}\n`,
    });
  }

  return result;
}

