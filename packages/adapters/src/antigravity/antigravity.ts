export function generateAntigravityRules(
  config: ResolvedCdalConfig,
): Array<{ path: string; content: string }> {
  const verifySteps = config.verify.map((v) => `- \`${v}\``).join('\n');
  const forbiddenSummary = config.forbidden.map((f) => `- \`${f.id}\`: ${f.msg}`).join('\n');

  const content = `<!-- GENERATED by cdal sync — do not edit directly. -->
# CDAL Quality Gates for Antigravity & Gemini Agents

This project operates under the Contract-Driven Agentic Loop (CDAL).

## 1. Core Principles
- **Contracts as Single Source of Truth**: All invariants live in \`${config.contractsDir}/*.contract.mjs\`.
- **Role Scopes**: Respect designated write scopes. Implementers must NEVER modify tests.
- **Traceability**: All test cases must specify their requirement: \`// @REQ: <ID>\`.

## 2. Verification Pipeline
${verifySteps}

## 3. Forbidden Patterns
${forbiddenSummary || '- Strict TypeScript: no `@ts-ignore`, no `as any`'}

## 4. Phase Gates
Always run \`npx cdal phase <contract|red|green>\` to verify git diff compliance.
`;

  if (content.length > ANTIGRAVITY_RULES_CHAR_LIMIT) {
    throw new Error(
      `Generated Antigravity rules file exceeds ${ANTIGRAVITY_RULES_CHAR_LIMIT} char limit (${content.length} chars).`,
    );
  }

  return [
    {
      path: '.agents/rules/00-cdal-core.md',
      content,
    },
  ];
}

export function generateAntigravityFiles(
  config: ResolvedCdalConfig,
): Array<{ path: string; content: string }> {
  return [
    ...generateAntigravityAgents(config),
    ...generateAntigravityWorkflows(),
    ...generateAntigravityRules(config),
  ];
}
