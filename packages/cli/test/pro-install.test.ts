import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { ProInstallError, installPro } from '../src/pro/install.js';

function write(file: string, content: string) {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content, 'utf8');
}

describe('cdalkit pro install', () => {
  let sourceDir: string;
  let targetDir: string;

  beforeEach(() => {
    const base = join(
      tmpdir(),
      `cdal-pro-test-${Date.now()}-${Math.random().toString(36).slice(2)}`,
    );
    sourceDir = join(base, 'cdal-pro');
    targetDir = join(base, 'project');
    mkdirSync(targetDir, { recursive: true });
    write(
      join(sourceDir, 'pro.manifest.json'),
      JSON.stringify({
        name: 'cdal-pro',
        version: '0.1.0',
        install: [
          { from: 'agents/claude', to: '.claude/agents' },
          { from: 'workorders', to: 'docs/workorders/templates' },
        ],
      }),
    );
    write(join(sourceDir, 'agents/claude/reviewer.md'), '# reviewer');
    write(join(sourceDir, 'agents/claude/nested/e2e-runner.md'), '# e2e');
    write(join(sourceDir, 'workorders/feature.md'), '# WO');
  });

  afterEach(() => {
    rmSync(dirname(sourceDir), { recursive: true, force: true });
  });

  // @REQ: CDAL-REQ-PRO-INSTALL
  it('copies every manifest mapping and records the installed version', () => {
    const result = installPro({ sourceDir, targetDir });

    expect(result.version).toBe('0.1.0');
    expect(result.written.sort()).toEqual([
      '.claude/agents/nested/e2e-runner.md',
      '.claude/agents/reviewer.md',
      'docs/workorders/templates/feature.md',
    ]);
    expect(readFileSync(join(targetDir, '.claude/agents/reviewer.md'), 'utf8')).toBe('# reviewer');

    const record = JSON.parse(readFileSync(join(targetDir, '.cdal/pro.json'), 'utf8'));
    expect(record.name).toBe('cdal-pro');
    expect(record.version).toBe('0.1.0');
    expect(record.files).toContain('docs/workorders/templates/feature.md');
  });

  // @REQ: CDAL-REQ-PRO-INSTALL
  it('never overwrites existing files unless force is set', () => {
    write(join(targetDir, '.claude/agents/reviewer.md'), '# my customized reviewer');

    const first = installPro({ sourceDir, targetDir });
    expect(first.skipped).toEqual(['.claude/agents/reviewer.md']);
    expect(readFileSync(join(targetDir, '.claude/agents/reviewer.md'), 'utf8')).toBe(
      '# my customized reviewer',
    );

    const forced = installPro({ sourceDir, targetDir, force: true });
    expect(forced.skipped).toEqual([]);
    expect(readFileSync(join(targetDir, '.claude/agents/reviewer.md'), 'utf8')).toBe('# reviewer');
  });

  // @REQ: CDAL-REQ-PRO-INSTALL
  it('replaces role files generated by cdalkit sync, but keeps user-owned ones', () => {
    write(
      join(targetDir, '.claude/agents/reviewer.md'),
      '---\nname: reviewer\n---\n<!-- CDAL GENERATED AGENT ROLE: reviewer -->\nGeneric\n',
    );
    write(join(targetDir, 'docs/workorders/templates/feature.md'), '# my own template');

    const result = installPro({ sourceDir, targetDir });

    expect(readFileSync(join(targetDir, '.claude/agents/reviewer.md'), 'utf8')).toBe('# reviewer');
    expect(result.skipped).toEqual(['docs/workorders/templates/feature.md']);
  });

  // @REQ: CDAL-REQ-PRO-INSTALL
  it('writes nothing in dry-run mode', () => {
    const result = installPro({ sourceDir, targetDir, dryRun: true });

    expect(result.written).toHaveLength(3);
    expect(existsSync(join(targetDir, '.claude'))).toBe(false);
    expect(existsSync(join(targetDir, '.cdal/pro.json'))).toBe(false);
  });

  // @REQ: CDAL-REQ-PRO-INSTALL
  it('rejects manifest paths that escape the source or project directory', () => {
    for (const mapping of [
      { from: '../outside', to: 'docs' },
      { from: 'agents/claude', to: '../../etc' },
      { from: 'agents/claude', to: '/tmp/abs' },
    ]) {
      write(
        join(sourceDir, 'pro.manifest.json'),
        JSON.stringify({ name: 'cdal-pro', version: '0.1.0', install: [mapping] }),
      );
      expect(() => installPro({ sourceDir, targetDir })).toThrow(ProInstallError);
    }
  });

  // @REQ: CDAL-REQ-PRO-INSTALL
  it('fails with a clear error when the manifest is missing', () => {
    rmSync(join(sourceDir, 'pro.manifest.json'));
    expect(() => installPro({ sourceDir, targetDir })).toThrow(/pro\.manifest\.json/);
  });
});
