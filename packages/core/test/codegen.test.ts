import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { ContractRegistry, defineKind, runCodegen } from '../src/index.js';

describe('Codegen Engine & Drift Detection (CDK-E1-CODEGEN)', () => {
  let tmpDir: string;

  beforeEach(() => {
    tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'cdal-codegen-test-'));
  });

  afterEach(() => {
    fs.rmSync(tmpDir, { recursive: true, force: true });
  });

  function createTestKind() {
    return defineKind({
      id: 'entity',
      files: ['entity.contract.mjs'],
      load: () => ({ entities: ['User', 'Account'] }),
      rules: [],
      emit: (data, ctx) => {
        if (ctx.target === 'ts') {
          return [
            {
              path: 'entities.ts',
              content:
                '// @generated by CDAL\nexport const ENTITIES = ["User", "Account"] as const;\n',
            },
          ];
        }
        if (ctx.target === 'docs') {
          return [
            {
              path: 'entities.md',
              content: '# Entities\n\n- User\n- Account\n',
            },
          ];
        }
        return [];
      },
      mutations: [],
    });
  }

  // @REQ: CDAL-REQ-CODEGEN
  it('writes generated files to configured target directories', async () => {
    const contractsDir = path.join(tmpDir, 'contracts');
    fs.mkdirSync(contractsDir, { recursive: true });
    fs.writeFileSync(path.join(contractsDir, 'entity.contract.mjs'), 'export default {};', 'utf8');

    const registry = new ContractRegistry();
    registry.register(createTestKind());

    const res = await runCodegen({
      contractsDir: 'contracts',
      generatedTsDir: 'src/generated',
      generatedDocsDir: 'docs/generated',
      check: false,
      cwd: tmpDir,
      registry,
    });

    expect(res.success).toBe(true);
    expect(res.drift).toBe(false);
    expect(res.files).toHaveLength(2);
    expect(res.files.every((f) => f.status === 'written')).toBe(true);

    const tsContent = fs.readFileSync(path.join(tmpDir, 'src/generated/entities.ts'), 'utf8');
    expect(tsContent).toBe(
      '// @generated by CDAL\nexport const ENTITIES = ["User", "Account"] as const;\n',
    );

    const docContent = fs.readFileSync(path.join(tmpDir, 'docs/generated/entities.md'), 'utf8');
    expect(docContent).toBe('# Entities\n\n- User\n- Account\n');
  });

  it('guarantees deterministic byte-for-byte emission across multiple runs', async () => {
    const contractsDir = path.join(tmpDir, 'contracts');
    fs.mkdirSync(contractsDir, { recursive: true });
    fs.writeFileSync(path.join(contractsDir, 'entity.contract.mjs'), 'export default {};', 'utf8');

    const registry = new ContractRegistry();
    registry.register(createTestKind());

    await runCodegen({
      contractsDir: 'contracts',
      generatedTsDir: 'src/generated',
      generatedDocsDir: 'docs/generated',
      check: false,
      cwd: tmpDir,
      registry,
    });

    const run1 = fs.readFileSync(path.join(tmpDir, 'src/generated/entities.ts'), 'utf8');

    await runCodegen({
      contractsDir: 'contracts',
      generatedTsDir: 'src/generated',
      generatedDocsDir: 'docs/generated',
      check: false,
      cwd: tmpDir,
      registry,
    });

    const run2 = fs.readFileSync(path.join(tmpDir, 'src/generated/entities.ts'), 'utf8');
    expect(run1).toBe(run2);
  });

  it('--check passes when files on disk match exactly', async () => {
    const contractsDir = path.join(tmpDir, 'contracts');
    fs.mkdirSync(contractsDir, { recursive: true });
    fs.writeFileSync(path.join(contractsDir, 'entity.contract.mjs'), 'export default {};', 'utf8');

    const registry = new ContractRegistry();
    registry.register(createTestKind());

    // Generate first
    await runCodegen({
      contractsDir: 'contracts',
      generatedTsDir: 'src/generated',
      generatedDocsDir: 'docs/generated',
      check: false,
      cwd: tmpDir,
      registry,
    });

    // Check should pass
    const checkRes = await runCodegen({
      contractsDir: 'contracts',
      generatedTsDir: 'src/generated',
      generatedDocsDir: 'docs/generated',
      check: true,
      cwd: tmpDir,
      registry,
    });

    expect(checkRes.success).toBe(true);
    expect(checkRes.drift).toBe(false);
    expect(checkRes.files.every((f) => f.status === 'unchanged')).toBe(true);
  });

  it('--check detects missing generated files', async () => {
    const contractsDir = path.join(tmpDir, 'contracts');
    fs.mkdirSync(contractsDir, { recursive: true });
    fs.writeFileSync(path.join(contractsDir, 'entity.contract.mjs'), 'export default {};', 'utf8');

    const registry = new ContractRegistry();
    registry.register(createTestKind());

    // Run check without generating first
    const checkRes = await runCodegen({
      contractsDir: 'contracts',
      generatedTsDir: 'src/generated',
      generatedDocsDir: 'docs/generated',
      check: true,
      cwd: tmpDir,
      registry,
    });

    expect(checkRes.success).toBe(false);
    expect(checkRes.drift).toBe(true);
    expect(checkRes.files.some((f) => f.status === 'missing')).toBe(true);
  });

  it('--check detects manual modifications (drift)', async () => {
    const contractsDir = path.join(tmpDir, 'contracts');
    fs.mkdirSync(contractsDir, { recursive: true });
    fs.writeFileSync(path.join(contractsDir, 'entity.contract.mjs'), 'export default {};', 'utf8');

    const registry = new ContractRegistry();
    registry.register(createTestKind());

    // Generate first
    await runCodegen({
      contractsDir: 'contracts',
      generatedTsDir: 'src/generated',
      generatedDocsDir: 'docs/generated',
      check: false,
      cwd: tmpDir,
      registry,
    });

    // Manually edit generated file
    const targetFile = path.join(tmpDir, 'src/generated/entities.ts');
    fs.writeFileSync(targetFile, '// MANUALLY MODIFIED BY SOME AGENT\n', 'utf8');

    // Run check
    const checkRes = await runCodegen({
      contractsDir: 'contracts',
      generatedTsDir: 'src/generated',
      generatedDocsDir: 'docs/generated',
      check: true,
      cwd: tmpDir,
      registry,
    });

    expect(checkRes.success).toBe(false);
    expect(checkRes.drift).toBe(true);
    const drifted = checkRes.files.find((f) => f.path === 'entities.ts');
    expect(drifted?.status).toBe('drift');
  });
});
