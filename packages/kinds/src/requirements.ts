import type { ContractKind, EmitCtx, Finding, GeneratedFile, Mutation, Rule } from '@cdal/core';

export type RequirementStatus = 'TODO' | 'IMPLEMENTING' | 'DONE' | 'BLOCKED' | 'SUPERSEDED';
export type RequirementPriority = 'CRITICAL' | 'HIGH' | 'MEDIUM' | 'LOW';

export interface Requirement {
  id: string;
  source: string;
  statement: string;
  acceptance: string[];
  status: RequirementStatus;
  priority?: RequirementPriority;
  parent?: string;
  tags?: string[];
}

export interface RequirementsData {
  requirements: Requirement[];
}

const findDuplicates = (arr: string[]): string[] => {
  const seen = new Set<string>();
  const dupes = new Set<string>();
  for (const item of arr) {
    if (seen.has(item)) dupes.add(item);
    else seen.add(item);
  }
  return Array.from(dupes);
};

const VALID_STATUSES: Set<RequirementStatus> = new Set([
  'TODO',
  'IMPLEMENTING',
  'DONE',
  'BLOCKED',
  'SUPERSEDED',
]);

export const requirementsRules: Rule<RequirementsData>[] = [
  {
    id: 'REQ-UNIQUE-IDS',
    severity: 'error',
    check(data): Finding[] {
      const findings: Finding[] = [];
      const ids = data.requirements.map((r) => r.id);
      const dupes = findDuplicates(ids);
      if (dupes.length > 0) {
        findings.push({
          ruleId: 'REQ-UNIQUE-IDS',
          severity: 'error',
          message: `Duplicate requirement IDs detected: ${dupes.join(', ')}`,
        });
      }
      return findings;
    },
  },
  {
    id: 'REQ-COMPLETE',
    severity: 'error',
    check(data): Finding[] {
      const findings: Finding[] = [];
      for (const r of data.requirements) {
        if (!r.id || r.id.trim() === '') {
          findings.push({
            ruleId: 'REQ-COMPLETE',
            severity: 'error',
            message: 'Requirement entry is missing a valid "id".',
          });
        }
        if (!r.source || r.source.trim() === '') {
          findings.push({
            ruleId: 'REQ-COMPLETE',
            severity: 'error',
            message: `Requirement "${r.id || 'unknown'}": missing "source" document reference.`,
          });
        }
        if (!r.statement || r.statement.trim() === '') {
          findings.push({
            ruleId: 'REQ-COMPLETE',
            severity: 'error',
            message: `Requirement "${r.id}": missing "statement" text.`,
          });
        }
        if (!Array.isArray(r.acceptance) || r.acceptance.length === 0) {
          findings.push({
            ruleId: 'REQ-COMPLETE',
            severity: 'error',
            message: `Requirement "${r.id}": missing "acceptance" criteria array. Tests cannot be derived.`,
          });
        }
      }
      return findings;
    },
  },
  {
    id: 'REQ-STATUS-VALID',
    severity: 'error',
    check(data): Finding[] {
      const findings: Finding[] = [];
      for (const r of data.requirements) {
        if (!VALID_STATUSES.has(r.status)) {
          findings.push({
            ruleId: 'REQ-STATUS-VALID',
            severity: 'error',
            message: `Requirement "${r.id}": invalid status "${r.status}". Allowed statuses: ${Array.from(VALID_STATUSES).join(', ')}.`,
          });
        }
      }
      return findings;
    },
  },
  {
    id: 'REQ-PARENT-EXISTS',
    severity: 'error',
    check(data): Finding[] {
      const findings: Finding[] = [];
      const ids = new Set(data.requirements.map((r) => r.id));
      for (const r of data.requirements) {
        if (r.parent && !ids.has(r.parent)) {
          findings.push({
            ruleId: 'REQ-PARENT-EXISTS',
            severity: 'error',
            message: `Requirement "${r.id}": parent requirement "${r.parent}" does not exist.`,
          });
        }
      }
      return findings;
    },
  },
];

export const requirementsMutations: Mutation[] = [
  {
    rule: 'REQ-UNIQUE-IDS',
    file: 'requirements.contract.mjs',
    find: /(id:\s*['"]([A-Za-z0-9_-]+)['"][\s\S]*?id:\s*['"])[A-Za-z0-9_-]+(['"])/,
    replace: '$1$2$3',
  },
  {
    rule: 'REQ-COMPLETE',
    file: 'requirements.contract.mjs',
    find: /statement:\s*['"][^'"]+['"]/,
    replace: "statement: ''",
  },
  {
    rule: 'REQ-STATUS-VALID',
    file: 'requirements.contract.mjs',
    find: /status:\s*['"][A-Z_]+['"]/,
    replace: "status: 'INVALID_STATUS'",
  },
  {
    rule: 'REQ-PARENT-EXISTS',
    file: 'requirements.contract.mjs',
    find: /status:\s*['"][A-Z_]+['"]/,
    replace: "status: 'TODO', parent: 'NON_EXISTENT_PARENT'",
  },
];

export function emitRequirements(data: RequirementsData, ctx: EmitCtx): GeneratedFile[] {
  if (ctx.target === 'ts') {
    const sorted = [...data.requirements].sort((a, b) => a.id.localeCompare(b.id));
    const ids = sorted.map((r) => `  | '${r.id}'`).join('\n');
    const content = `// @generated by CDAL (Contract-Driven Agentic Loop)
// Do not edit manually - changes will be overwritten by 'cdal codegen'.

export type RequirementId =
${ids};

export const REQUIREMENTS = ${JSON.stringify(sorted, null, 2)} as const;
`;
    return [{ path: 'requirements.ts', content }];
  }

  if (ctx.target === 'docs') {
    const sorted = [...data.requirements].sort((a, b) => a.id.localeCompare(b.id));
    let md = '# System Requirements Matrix\n\n';
    md += '| ID | Status | Priority | Statement | Acceptance Criteria |\n';
    md += '|---|---|---|---|---|\n';
    for (const r of sorted) {
      const criteria = (r.acceptance || []).map((c, i) => `${i + 1}. ${c}`).join('<br>');
      md += `| **${r.id}** | \`${r.status}\` | ${r.priority || 'NORMAL'} | ${r.statement} | ${criteria} |\n`;
    }
    return [{ path: 'requirements.md', content: md }];
  }

  return [];
}

export function requirements(options?: { file?: string }): ContractKind<RequirementsData> {
  const file = options?.file ?? 'requirements.contract.mjs';

  return {
    id: 'requirements',
    files: [file],
    load(mod): RequirementsData {
      const candidate = mod.REQUIREMENTS ?? mod.default;
      const list = Array.isArray(candidate)
        ? candidate
        : candidate && typeof candidate === 'object' && 'requirements' in candidate
          ? (candidate as { requirements: unknown }).requirements
          : candidate;

      if (!Array.isArray(list)) {
        throw new Error('requirements contract must export an array "REQUIREMENTS".');
      }
      return { requirements: list as Requirement[] };
    },
    rules: requirementsRules,
    emit: emitRequirements,
    mutations: requirementsMutations.map((m) => ({ ...m, file })),
  };
}
