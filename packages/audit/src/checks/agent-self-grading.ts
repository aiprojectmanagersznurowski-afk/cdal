import { execSync } from 'node:child_process';
import type { WorkspaceFiles } from '../crawler.js';
import type { AuditCheckResult, AuditFinding } from '../types.js';

interface ParsedCommit {
  hash: string;
  subject: string;
  body: string;
  isAi: boolean;
  files: string[];
}

export function checkAgentSelfGrading(
  files: WorkspaceFiles,
  weight = 15,
  maxCommits = 200,
): AuditCheckResult {
  const findings: AuditFinding[] = [];

  let gitOutput = '';
  try {
    gitOutput = execSync(
      `git log -n ${maxCommits} --format="COMMIT:%h%x01%s%x01%b%x01FILES:" --name-only`,
      { cwd: files.cwd, encoding: 'utf8', timeout: 5000, stdio: ['ignore', 'pipe', 'ignore'] },
    );
  } catch {
    // Git log failed or not a git repository
    return {
      id: 'agent-self-grading',
      name: 'Agent grades itself (code and tests edited together)',
      weight,
      score: weight,
      maxScore: weight,
      passed: true,
      details: 'No git history or not a git repository (commit analysis skipped).',
      findings: [
        {
          message:
            'Skipped git commit analysis — the repository has no git history or the git binary is missing.',
          severity: 'info',
        },
      ],
      docsUrl: 'https://cdal.dev/docs/concepts/roles#separation-of-phases',
    };
  }

  const aiRegex =
    /(?:co-authored-by:\s*.*(?:claude|cursor|copilot|aider|gemini|codex|agent|ai|chatgpt|devin)|generated by.*(?:claude|cursor|copilot|ai))/i;
  const testFileRegex = /(?:\.test\.|\.spec\.|(?:^|\/)(?:test|tests)\/)/i;
  const prodFileRegex = /(?:^|\/)(?:src|lib|app|packages\/[^/]+\/src)\//i;

  const rawBlocks = gitOutput.split('COMMIT:').filter((b) => b.trim().length > 0);
  const commits: ParsedCommit[] = [];

  for (const block of rawBlocks) {
    const parts = block.split('\x01');
    if (parts.length < 3) continue;

    const hash = parts[0]?.trim() || '';
    const subject = parts[1]?.trim() || '';
    const remainder = parts[2] || '';

    const bodyAndFiles = remainder.split('FILES:');
    const body = bodyAndFiles[0]?.trim() || '';
    const filesList = (bodyAndFiles[1] || '')
      .split('\n')
      .map((f) => f.trim())
      .filter((f) => f.length > 0);

    const isAi = aiRegex.test(subject) || aiRegex.test(body);

    commits.push({
      hash,
      subject,
      body,
      isAi,
      files: filesList,
    });
  }

  const aiCommits = commits.filter((c) => c.isAi);
  let mixedCommits = 0;

  for (const commit of aiCommits) {
    const hasTests = commit.files.some((f) => testFileRegex.test(f));
    const hasProd = commit.files.some((f) => prodFileRegex.test(f));

    if (hasTests && hasProd) {
      mixedCommits++;
      if (findings.length < 10) {
        findings.push({
          message: `Commit [${commit.hash}] "${commit.subject.slice(0, 60)}" changed production code and tests together!`,
          severity: 'error',
        });
      }
    }
  }

  let score = 0;
  let details = '';

  if (commits.length === 0) {
    score = weight;
    details = 'No commits in git history to analyze.';
  } else if (aiCommits.length === 0) {
    score = weight;
    details = `Analyzed the last ${commits.length} commits — none were marked as authored by AI agents.`;
  } else {
    const mixedRatio = mixedCommits / aiCommits.length;
    const mixedPercent = Math.round(mixedRatio * 100);

    if (mixedCommits === 0) {
      score = weight;
      details = `Analyzed ${aiCommits.length} AI commits (out of ${commits.length}). 0% mixed tests with production code (clean RED/GREEN phases).`;
    } else if (mixedRatio <= 0.1) {
      score = Math.round(weight * 0.67);
      details = `${mixedCommits}/${aiCommits.length} AI commits (${mixedPercent}%) changed tests and production code together.`;
    } else if (mixedRatio <= 0.25) {
      score = Math.round(weight * 0.33);
      details = `${mixedCommits}/${aiCommits.length} AI commits (${mixedPercent}%) changed tests and production code together.`;
    } else {
      score = 0;
      details = `Critical risk: ${mixedCommits}/${aiCommits.length} AI commits (${mixedPercent}%) changed tests and production code together. The agent set and moved its own success criteria.`;
    }
  }

  return {
    id: 'agent-self-grading',
    name: 'Role and phase separation: “agent grades itself”',
    weight,
    score,
    maxScore: weight,
    passed: score >= weight * 0.7,
    details,
    findings,
    docsUrl: 'https://cdal.dev/docs/concepts/roles#separation-of-phases',
  };
}
